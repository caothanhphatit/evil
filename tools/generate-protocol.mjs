import { promises as fs } from "node:fs";

const schema = JSON.parse(await fs.readFile("packages/protocol/world-v1.schema.json", "utf8"));
const banner = "// Generated by tools/generate-protocol.mjs. Do not edit directly.\n";
const protocolVersion = schema.schemaVersion;
const maxMessageBytes = schema.wire.maxMessageBytes;

const commandVariants = schema.clientCommands.map((command) => {
  const fields = command.fields.map((field) => `${field.wireName}: ${field.tsType}`).join("; ");
  return `  | { type: "${command.wireName}"${fields ? `; ${fields}` : ""} }`;
});

const typescript = `${banner}
export const PROTOCOL_VERSION = ${protocolVersion} as const;
export const MAX_MESSAGE_BYTES = ${maxMessageBytes} as const;

export type OriginalScreen = "boot" | "village" | "hunter_roster" | "field";
export type BottomMenuIntent = "build" | "character" | "archive" | "store" | "raid";
export type BindingConfidence = "confirmed" | "strongly_inferred" | "tentative" | "unknown";
export type WorldMode = "inactive" | "village" | "field";
export type WorldEntityKind = "hunter" | "npc" | "monster";
export type Facing = "left" | "right";

export interface EvidenceBinding {
  id: string;
  confidence: BindingConfidence;
  resolved: boolean;
}

export interface VillageSnapshot {
  source_scene: "level1";
  canvas_nodes: string[];
  world_nodes: string[];
  bottom_menu: BottomMenuIntent[];
  bindings: EvidenceBinding[];
}

export interface HunterRosterSnapshot {
  scene_nodes: string[];
  hunter_spine_source_confirmed: boolean;
  starter_composition_resolved: boolean;
  starter_stats_resolved: boolean;
  bindings: EvidenceBinding[];
}

export interface FieldSnapshot {
  scene_nodes: string[];
  visual_projection_runnable: boolean;
  gameplay_runnable: false;
  blockers: string[];
}

export interface WorldEntityDescriptor {
  entity_id: string;
  kind: WorldEntityKind;
  asset_bundle_id: string;
  source_skeleton_name: string;
  role: "migration_visual_candidate";
  source_binding: EvidenceBinding;
  placement_binding: EvidenceBinding;
}

export interface WorldEntityProjection {
  descriptor: WorldEntityDescriptor;
  x: number;
  y: number;
  facing: Facing;
  animation: string;
  selectable: boolean;
}

export interface WorldProjection {
  mode: WorldMode;
  visual_tick: number;
  coordinate_space: "normalized_viewport_1000";
  authority_scope: "visual_roaming_only";
  entities: WorldEntityProjection[];
  selected_entity_id: string | null;
}

export interface OriginalFlowSnapshot {
  screen: OriginalScreen;
  content_release_id: "original-flow-v1";
  content_release_runnable: false;
  flow_order: OriginalScreen[];
  village: VillageSnapshot;
  hunter_roster: HunterRosterSnapshot;
  field: FieldSnapshot;
  world: WorldProjection;
}

export type ClientCommand =
${commandVariants.join("\n")};

export type ServerMessage =
  | { type: "welcome"; player_token: string; session_id: string; snapshot: OriginalFlowSnapshot }
  | { type: "resync"; snapshot: OriginalFlowSnapshot }
  | { type: "world_update"; snapshot: OriginalFlowSnapshot }
  | { type: "intent_result"; intent: string; accepted: boolean; reason: string | null; snapshot: OriginalFlowSnapshot }
  | { type: "binding_blocked"; intent: string; blockers: string[]; snapshot: OriginalFlowSnapshot };

export interface ClientEnvelope {
  version: typeof PROTOCOL_VERSION;
  sequence: number;
  session_id: string | null;
  correlation_id: string;
  payload: ClientCommand;
}

export interface ServerEnvelope {
  version: typeof PROTOCOL_VERSION;
  sequence: number;
  session_id: string;
  correlation_id: string | null;
  payload: ServerMessage;
}
`;

const rustCommands = schema.clientCommands.map((command) => {
  if (command.fields.length === 0) return `    ${command.rustName},`;
  const fields = command.fields.map((field) => `${field.wireName}: ${field.rustType}`).join(", ");
  return `    ${command.rustName} { ${fields} },`;
});

const rust = `${banner}
use serde::{Deserialize, Serialize};
use uuid::Uuid;

use super::{BottomMenuIntent, OriginalFlowSnapshot};

pub const PROTOCOL_VERSION: u16 = ${protocolVersion};
pub const MAX_MESSAGE_BYTES: usize = ${maxMessageBytes};

#[derive(Debug, Deserialize)]
#[serde(tag = "type", rename_all = "snake_case", deny_unknown_fields)]
pub enum ClientCommand {
${rustCommands.join("\n")}
}

#[derive(Debug, Serialize)]
#[serde(tag = "type", rename_all = "snake_case")]
pub enum ServerMessage {
    Welcome { player_token: Uuid, session_id: Uuid, snapshot: OriginalFlowSnapshot },
    Resync { snapshot: OriginalFlowSnapshot },
    WorldUpdate { snapshot: OriginalFlowSnapshot },
    IntentResult { intent: String, accepted: bool, reason: Option<String>, snapshot: OriginalFlowSnapshot },
    BindingBlocked { intent: String, blockers: Vec<String>, snapshot: OriginalFlowSnapshot },
}

#[derive(Debug, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct ClientEnvelope {
    pub version: u16,
    pub sequence: u64,
    pub session_id: Option<Uuid>,
    pub correlation_id: Uuid,
    pub payload: ClientCommand,
}

#[derive(Debug, Serialize)]
pub struct ServerEnvelope<'a> {
    pub version: u16,
    pub sequence: u64,
    pub session_id: Uuid,
    pub correlation_id: Option<Uuid>,
    pub payload: &'a ServerMessage,
}
`;

await fs.mkdir("apps/web/src/generated", { recursive: true });
await fs.writeFile("apps/web/src/generated/protocol.ts", typescript);
await fs.writeFile("apps/server/src/simulation/protocol.generated.rs", rust);
console.log(`Generated protocol v${schema.schemaVersion} for TypeScript and Rust.`);
