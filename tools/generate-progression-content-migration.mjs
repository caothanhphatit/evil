import { readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";

const root = resolve(import.meta.dirname, "..");
const sourcePath = resolve(root, "packages/content/releases/evil-hunter-1.411/experience-runtime-catalog.json");
const outputPath = resolve(root, "infra/db/migrations/0032_progression_content_catalog.sql");
const downPath = resolve(root, "infra/db/migrations/0032_progression_content_catalog.down.sql");
const source = JSON.parse(await readFile(sourcePath, "utf8"));

if (source.catalogId !== "evil-hunter-1.411.experience-runtime-v1" || !Array.isArray(source.rows)) {
  throw new Error("Unexpected progression catalog identity");
}
source.rows.forEach((row, index) => {
  if (row.index !== index || !Array.isArray(row.experienceByDifficulty) || row.experienceByDifficulty.length !== 6) {
    throw new Error(`Invalid progression row ${index}`);
  }
});

const values = source.rows.flatMap((row) => row.experienceByDifficulty.map((required, reviveTier) =>
  `    ('evil-hunter-1.411.buildings-v1', '${source.catalogId}', ${row.index}, ${reviveTier}, ${required})`,
));
const sql = `-- Generated by tools/generate-progression-content-migration.mjs. Do not hand-edit rows.
CREATE TABLE hunter_progression_definition (
    release_id TEXT NOT NULL REFERENCES content_release(release_id) ON DELETE CASCADE,
    progression_id TEXT NOT NULL CHECK (btrim(progression_id) <> ''),
    max_stored_level INTEGER NOT NULL CHECK (max_stored_level >= 0),
    display_level_offset INTEGER NOT NULL,
    PRIMARY KEY (release_id, progression_id)
);

CREATE TABLE hunter_progression_experience (
    release_id TEXT NOT NULL,
    progression_id TEXT NOT NULL,
    level_index INTEGER NOT NULL CHECK (level_index >= 0),
    revive_tier INTEGER NOT NULL CHECK (revive_tier BETWEEN 0 AND 5),
    required_experience BIGINT NOT NULL CHECK (required_experience >= 0),
    PRIMARY KEY (release_id, progression_id, level_index, revive_tier),
    FOREIGN KEY (release_id, progression_id)
        REFERENCES hunter_progression_definition(release_id, progression_id) ON DELETE CASCADE
);

INSERT INTO hunter_progression_definition
    (release_id, progression_id, max_stored_level, display_level_offset)
VALUES ('evil-hunter-1.411.buildings-v1', '${source.catalogId}', 99, 1);

INSERT INTO hunter_progression_experience
    (release_id, progression_id, level_index, revive_tier, required_experience)
VALUES
${values.join(",\n")};
`;

await writeFile(outputPath, sql);
await writeFile(downPath, "DROP TABLE IF EXISTS hunter_progression_experience;\nDROP TABLE IF EXISTS hunter_progression_definition;\n");
